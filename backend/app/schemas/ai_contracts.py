"""Pydantic Schemas strictly adhering to confirmed AI Engine output JSON contracts.

Confirmed AI Structures:
A. Vehicle Track JSON
B. Cross-Camera Match JSON
C. Global Vehicle JSON
D. Trajectory JSON
E. Route Prediction JSON

Note: No unsupported or fabricated fields are included.
"""
from typing import List, Optional, Any, Union
from pydantic import BaseModel, Field, ConfigDict, model_validator


class VehicleTrackInput(BaseModel):
    """Confirmed AI Vehicle Track item."""
    track_id: int = Field(..., description="Unique track ID generated by camera tracker")
    vehicle_class: str = Field(..., description="Classification e.g. Car, Sedan, Commercial SUV, etc.")
    plate_text: Optional[str] = Field(None, description="Extracted license plate text if OCR succeeded")
    plate_status: Optional[str] = Field("unknown", description="Plate status: stable, tentative, or unknown")
    plate_confidence: Optional[float] = Field(None, ge=0.0, le=100.0, description="Plate detection confidence score")
    observation_count: Optional[int] = Field(0, ge=0, description="Total frames track was observed")
    valid_observation_count: Optional[int] = Field(0, ge=0, description="Frames with valid vehicle features")
    best_ocr_confidence: Optional[float] = Field(None, ge=0.0, le=100.0, description="Highest OCR confidence attained")
    first_seen_frame: Optional[int] = Field(None, ge=0, description="Frame index of initial sighting")
    last_seen_frame: Optional[int] = Field(None, ge=0, description="Frame index of final sighting")
    last_bbox: Optional[List[int]] = Field(None, description="Bounding box coordinates [x1, y1, x2, y2]")
    detector_confidence: Optional[float] = Field(None, ge=0.0, le=1.0, description="Vehicle detector confidence score")

    @model_validator(mode="before")
    @classmethod
    def _normalize_track_input(cls, data: Any) -> Any:
        if isinstance(data, dict):
            d = dict(data)
            # Map frame_start / frame_end if first_seen_frame / last_seen_frame not present
            if "frame_start" in d and "first_seen_frame" not in d:
                d["first_seen_frame"] = d.pop("frame_start")
            if "frame_end" in d and "last_seen_frame" not in d:
                d["last_seen_frame"] = d.pop("frame_end")
            # Unpack nested plate dict if present
            if "plate" in d and isinstance(d["plate"], dict):
                p = d.pop("plate")
                if "plate_text" not in d:
                    d["plate_text"] = p.get("text")
                if "plate_status" not in d:
                    d["plate_status"] = p.get("status")
                if "plate_confidence" not in d:
                    d["plate_confidence"] = p.get("confidence")
                if "observation_count" not in d:
                    d["observation_count"] = p.get("observation_count")
                if "valid_observation_count" not in d:
                    d["valid_observation_count"] = p.get("valid_observation_count")
                if "best_ocr_confidence" not in d:
                    d["best_ocr_confidence"] = p.get("best_ocr_confidence")
            # Map observation_id -> track_id if track_id not present
            if "observation_id" in d and "track_id" not in d:
                parts = str(d["observation_id"]).split("_")
                try:
                    d["track_id"] = int(parts[-1])
                except (ValueError, IndexError):
                    d["track_id"] = 1
            # Map bbox -> last_bbox if last_bbox not present
            if "bbox" in d and "last_bbox" not in d:
                d["last_bbox"] = d.pop("bbox")
            # Pop extraneous fields from camera observation / reid dumps so extra="forbid" doesn't reject real AI outputs
            d.pop("observation_id", None)
            d.pop("image_name", None)
            d.pop("frame_index", None)
            d.pop("camera_metadata", None)
            d.pop("plate_bbox", None)
            d.pop("camera_id", None)
            d.pop("reid", None)
            d.pop("reid_embedding", None)
            d.pop("representative_embedding", None)
            d.pop("frame_count", None)
            return d
        return data

    model_config = ConfigDict(extra="forbid")


