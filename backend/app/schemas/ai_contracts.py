class CrossCameraMatchInput(BaseModel):
    """Confirmed AI Cross-Camera Match item."""
    camera_a: str = Field(..., description="First camera identifier")
    track_a: int = Field(..., description="Track ID in camera A")
    camera_b: str = Field(..., description="Second camera identifier")
    track_b: int = Field(..., description="Track ID in camera B")
    reid_similarity: Optional[float] = Field(None, ge=-1.0, le=1.0, description="Visual Re-ID embedding cosine similarity")
    plate_match: Optional[bool] = Field(None, description="Whether plate OCR texts match")
    class_match: Optional[Union[float, bool]] = Field(None, description="Whether vehicle classifications match")
    available_evidence: Optional[List[str]] = Field(default_factory=list, description="List of evidence types e.g. ['reid', 'class']")
    match_score: float = Field(..., ge=0.0, le=1.0, description="Combined fusion match score")
    threshold: float = Field(..., ge=0.0, le=1.0, description="Operational decision threshold")
    matched: bool = Field(..., description="Whether match was accepted above threshold")

    @model_validator(mode="before")
    @classmethod
    def _normalize_match_input(cls, data: Any) -> Any:
        if isinstance(data, dict):
            d = dict(data)
            if "observation_a" in d and "track_a" not in d:
                parts = str(d["observation_a"]).split("_")
                try:
                    d["track_a"] = int(parts[-1])
                except (ValueError, IndexError):
                    d["track_a"] = 1
            if "observation_b" in d and "track_b" not in d:
                parts = str(d["observation_b"]).split("_")
                try:
                    d["track_b"] = int(parts[-1])
                except (ValueError, IndexError):
                    d["track_b"] = 1
            if "threshold" not in d:
                d["threshold"] = 0.75
            d.pop("observation_a", None)
            d.pop("observation_b", None)
            d.pop("image_a", None)
            d.pop("image_b", None)
            d.pop("class_a", None)
            d.pop("class_b", None)
            d.pop("plate_a", None)
            d.pop("plate_b", None)
            d.pop("match_status", None)
            d.pop("reason", None)
            return d
        return data

    model_config = ConfigDict(extra="forbid")


